import assert from 'node:assert/strict';
import {transcriptWords, updatePhrase, changedTokens, wordsInRange} from '../web/dialogue_transcript.js';

const words=[{text:'eight',start:0,end:.5},{text:'pounds',start:.5,end:1},{text:'please',start:1,end:1.5}];
assert.deepEqual(wordsInRange(words,[.5,1]).map(w=>w.text),['pounds']);
assert.deepEqual(wordsInRange(words,[0,1]).map(w=>w.text),['eight','pounds']);
const state={sentence:'',edited:false};
assert.equal(updatePhrase(state,'clip-a','eight pounds please'),true);
state.sentence='eight euros please';state.edited=true;
assert.equal(updatePhrase(state,'clip-a','eight pounds please'),false);
assert.equal(updatePhrase(state,'clip-b','another recognised phrase'),false);
assert.equal(state.sentence,'eight euros please');
assert.equal(updatePhrase(state,'clip-b','another recognised phrase',true),true);
assert.equal(state.edited,false);
assert.equal(state.sentence,'another recognised phrase');
assert.equal(updatePhrase(state,'empty',''),false);
assert.equal(state.sentence,'another recognised phrase');
assert.deepEqual(changedTokens('eight pounds please','eight euros please'),[{text:'eight',added:false},{text:'euros',added:true},{text:'please',added:false}]);
assert.deepEqual(changedTokens('hello old friend','hello friend').map(t=>t.added),[false,false]);
assert.deepEqual(changedTokens('a b a','a x a').filter(t=>t.added).map(t=>t.text),['x']);
let requests=0,resolve;
const pending=new Promise(r=>resolve=r);
const fetcher=async()=>{requests++;await pending;return {ok:true,json:async()=>({words})};};
const first=transcriptWords(fetcher,'clip-a','identity-a'),second=transcriptWords(fetcher,'clip-a','identity-a');
resolve();assert.deepEqual(await first,words);assert.deepEqual(await second,words);assert.equal(requests,1);
await transcriptWords(fetcher,'clip-a','identity-b');assert.equal(requests,2);
let failures=0;
const retry=async()=>{failures++;return failures===1?{ok:false,json:async()=>({error:'offline'})}:{ok:true,json:async()=>({words})};};
await assert.rejects(transcriptWords(retry,'retry','1'),/offline/);
assert.deepEqual(await transcriptWords(retry,'retry','1'),words);
console.log('Automatic transcript, cached requests, retries, word ranges, edit highlighting and protected drafts passed.');
