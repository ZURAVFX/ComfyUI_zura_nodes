import assert from 'node:assert/strict';
import {aeFramePolicy,modelAEFrameContract,aeFrameConfig,bindAEFrameWorkspace} from '../web/studio_ae_frame_contract.js';

const config={engine:'h3',workflow_mode:'relight',relight_engine:'wan21',relight_shape:'source'};
const base=(count,numerator=25,denominator=1)=>({schemaVersion:1,sessionId:'a'.repeat(32),frameCount:count,trimFrames:count,modelFrames:count,width:1920,height:1080,frameRate:{numerator,denominator}});
const policy=aeFramePolicy('relight',config,{});
assert.equal(policy.nativeFPS,undefined);
assert.equal(policy.sections,true);
assert.equal(modelAEFrameContract(base(750),policy).modelFrames,753,'Thirty seconds can span native Wan windows');
assert.throws(()=>modelAEFrameContract(base(751),policy),/between 0.1 and 30 seconds/);
assert.throws(()=>modelAEFrameContract(base(2),policy),/between 0.1 and 30 seconds/);
assert.equal(modelAEFrameContract(base(3,30),policy).frameCount,3);
const ntsc=base(899,30000,1001),contract=modelAEFrameContract(ntsc,policy);
assert.equal(contract.modelFrames,901);
assert.deepEqual(contract.frameRate,ntsc.frameRate);
assert.equal(contract.frameCount,899);
assert.throws(()=>modelAEFrameContract(base(900,30000,1001),policy),/between 0.1 and 30 seconds/);
assert.throws(()=>modelAEFrameContract(base(9),aeFramePolicy('swap',{engine:'h3'})),/24 fps/,'Other H3 routes retain their native rate');
assert.equal(aeFramePolicy('relight',{engine:'ltx'},{state:{engine:'ltx'}}).max,985,'Edited-frame LTX Relight keeps its own policy');
const owner={aeFrameBase:base(9),aeFrameMode:'relight'};
const resolved=aeFrameConfig(owner,config);
assert.equal(resolved.duration,9/25);assert.equal(resolved.relight_shape,'source_size');
assert.equal(config.relight_shape,'source','The caller draft is not mutated');
const normal={...config};assert.equal(aeFrameConfig({},normal),normal,'Normal Studio remains unchanged');
const workspace={config:{...config},syncForm(){},save(){},render(){}};
const creative={studio:workspace};
bindAEFrameWorkspace(creative,'relight',workspace,base(9));
assert.equal(workspace.config.duration,9/25);assert.equal(workspace.config.relight_shape,'source_size');
assert.deepEqual(workspace.config.ae_frame_contract.frameRate,{numerator:25,denominator:1});
const legacy=aeFramePolicy('relight',{engine:'h3',workflow_mode:'relight',relight_engine:'h3'},{});
assert.equal(modelAEFrameContract(base(200),legacy).frameCount,200,'Legacy main Relight resolves to the same Wan route as the server');
console.log('Wan AE policy: source cadence, sectioned 0.1–30-second range, source-size delivery and other native route restrictions passed');
