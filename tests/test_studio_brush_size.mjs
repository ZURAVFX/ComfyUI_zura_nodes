import assert from 'node:assert/strict';
import {parseHTML} from '../../ui-check/node_modules/linkedom/esm/index.js';
import {BrushSizeControl} from '../web/studio_brush_size.js';

const {document}=parseHTML('<html><body><label>Size <input id="brush" type="range" min="1" max="1000" value="96"></label></body></html>');
const source=document.querySelector('#brush');let applied=0,current=96;
source.addEventListener('input',()=>{applied++;current=Number(source.value);});
const control=new BrushSizeControl(source);
assert.equal(source.type,'hidden');assert.equal(source.hidden,true);
assert.equal(control.slider.id,'brush');assert.equal(source.id,'');
assert.equal(control.number.value,'96');assert.equal(control.slider.getAttribute('aria-valuetext'),'96 px');
assert.equal(new BrushSizeControl(source),control,'Mounting an existing control must not add handlers or inputs');
assert.equal(document.querySelectorAll('[data-brush-size-slider]').length,1);
assert.equal(document.querySelectorAll('.pap-brush-number').length,1);
const key=(key,shiftKey=false)=>{let prevented=false;control.slider.onkeydown({key,shiftKey,preventDefault(){prevented=true;},stopPropagation(){}});assert.equal(prevented,true);};
key('ArrowRight');assert.equal(current,97);
key('ArrowLeft');assert.equal(current,96);
key('ArrowUp',true);assert.equal(current,106);
key('ArrowDown',true);assert.equal(current,96);
key('Home');assert.equal(current,1);
key('End');assert.equal(current,1000);
control.slider.value='500';control.slider.oninput();assert.equal(current,251);assert.equal(control.number.value,'251');
control.commit(-10);assert.equal(current,1);control.commit(10001);assert.equal(current,1000);
const before=applied;source.disabled=true;control.sync();
assert.equal(control.number.disabled,true);assert.equal(control.slider.disabled,true);control.commit(24);
assert.equal(applied,before);assert.equal(source.value,'1000');
source.disabled=false;source.value='144';source.dispatchEvent(new document.defaultView.Event('input'));
assert.equal(control.number.value,'144');assert.equal(control.slider.getAttribute('aria-valuetext'),'144 px');
assert.equal(control.number.disabled,false);assert.equal(control.slider.disabled,false);
const second=document.createElement('label');second.innerHTML='<input type="range" value="48"><input type="number" data-owned-number>';
document.body.append(second);const originalNumber=second.querySelector('[data-owned-number]');
const paired=new BrushSizeControl(second.querySelector('[type=range]'),{number:originalNumber});
assert.equal(paired.number,originalNumber);assert.equal(second.querySelectorAll('[type=number]').length,1);
console.log('Shared brush: original handlers retained, idempotent mounting, precise keyboard steps, nonlinear range, number sync, 1–1000 bounds and busy state passed');
