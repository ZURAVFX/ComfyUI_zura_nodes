import assert from 'node:assert/strict';
import fs from 'node:fs';
import {createLocalStudioAPI,requireSessionOrigin,verifyStudioHostManifest,unavailableGraphApp,STUDIO_HOST_SCHEMA} from '../web/studio_host_adapters.js';
import {scopedStudioAPI} from '../web/studio_ae_lifecycle.js';
import {AE_STUDIO_HOST} from '../web/studio_ae_entry.js';

const origin='http://127.0.0.1:8199',requests=[],sockets=[],timers=[];
class Socket{
  constructor(url){this.url=url;sockets.push(this);}
  close(){this.closed=true;}
}
const fetchImpl=async(url,options)=>{requests.push({url,options});return {ok:true,status:200,url,redirected:false,json:async()=>({}),text:async()=>''};};
const api=createLocalStudioAPI({origin,fetchImpl,WebSocketImpl:Socket,clientId:'ae-client',setTimer:fn=>{timers.push(fn);return timers.length;},clearTimer:()=>{}});
assert.equal(api.apiURL('/view?filename=x.png'),origin+'/view?filename=x.png');
assert.throws(()=>api.apiURL('https://remote.example/view'),/local ComfyUI paths/);
assert.throws(()=>api.apiURL('//remote.example/view'),/local ComfyUI paths/);
assert.throws(()=>api.apiURL('/admin'),/local ComfyUI paths/);
assert.throws(()=>createLocalStudioAPI({origin:'http://localhost:8199'}),/verified local/);
const session={id:'a'.repeat(32),capability:'b'.repeat(64),comfyOrigin:origin,modes:{registry:'native_studio',source:true,transfer:true}};
assert.equal(requireSessionOrigin(session,origin),session);
assert.throws(()=>requireSessionOrigin({...session,comfyOrigin:'http://127.0.0.1:8200'},origin),/does not match/);
assert.throws(()=>requireSessionOrigin({...session,modes:{registry:'other',source:true,transfer:true}},origin),/native Studio source/);
const scoped=scopedStudioAPI(api,session);
await scoped.api.fetchApi('/prompt',{method:'POST',body:'{}'});
assert.equal(requests[0].url,origin+'/prompt');
assert.equal(requests[0].options.redirect,'error');
assert.equal(requests[0].options.headers.get('X-ComfyLink-Studio-Id'),session.id);
assert.equal(requests[0].options.headers.get('X-ComfyLink-Studio-Session'),session.capability);
const proxyRequests=[],proxyOrigin='http://127.0.0.1:8222';
const proxyAPI=createLocalStudioAPI({origin:proxyOrigin,fetchImpl:async(url,options)=>{proxyRequests.push({url,options});return {ok:true,url,redirected:false};},clientId:'proxy-client'});
const proxyScope=scopedStudioAPI(proxyAPI,session,{uiOrigin:proxyOrigin});
await proxyScope.api.fetchApi('/prompt',{method:'POST'});
assert.equal(proxyRequests[0].url,proxyOrigin+'/prompt','Verified proxy requests stay on the UI origin');
assert.equal(proxyRequests[0].options.headers.get('X-ComfyLink-Studio-Session'),session.capability);
assert.throws(()=>scopedStudioAPI(proxyAPI,session,{uiOrigin:'https://remote.example'}),/verified local origin/);
proxyScope.end();proxyAPI.dispose();
await scoped.api.fetchApi('/history/owned-id');
await scoped.api.fetchApi('/queue');
await scoped.api.fetchApi('/view?filename=x.png');
await scoped.api.fetchApi('/zura/comfylink/v1/studio/sessions/'+session.id+'/source');
assert.deepEqual(requests.slice(1).map(r=>new URL(r.url).pathname),['/history/owned-id','/queue','/view','/zura/comfylink/v1/studio/sessions/'+session.id+'/source']);
await assert.rejects(()=>scoped.api.fetchApi('https://remote.example/view'),/local ComfyUI server/);
const received=[];
for(const type of ['progress','executing','execution_error','b_preview'])api.addEventListener(type,event=>received.push({type,detail:event.detail}));
api.start();
assert.equal(sockets.length,1);
assert.equal(sockets[0].url,'ws://127.0.0.1:8199/ws?clientId=ae-client');
sockets[0].onmessage({data:JSON.stringify({type:'progress',data:{prompt_id:'owned-id',value:3,max:10}})});
sockets[0].onmessage({data:JSON.stringify({type:'executing',data:{prompt_id:'owned-id',node:'sampler'}})});
sockets[0].onmessage({data:JSON.stringify({type:'execution_error',data:{prompt_id:'owned-id',exception_message:'failure'}})});
const binary=new ArrayBuffer(11),view=new DataView(binary);view.setUint32(0,1);view.setUint32(4,1);new Uint8Array(binary).set([1,2,3],8);
await sockets[0].onmessage({data:new Blob([binary])});
assert.deepEqual(received.slice(0,3).map(e=>e.type),['progress','executing','execution_error']);
assert.equal(received[0].detail.prompt_id,'owned-id');
assert.equal(received[3].detail.type,'image/jpeg');
assert.equal(received[3].detail.size,3);
sockets[0].onclose();assert.equal(timers.length,1);
api.dispose();timers[0]();assert.equal(sockets.length,1,'Disposed AE connection does not reconnect');
await assert.rejects(()=>api.fetchApi('/history'),{name:'AbortError'});
scoped.end();await assert.rejects(()=>scoped.api.fetchApi('/prompt'),{name:'AbortError'});
assert.throws(()=>unavailableGraphApp().loadApiJson({}),/Open Studio in ComfyUI/);
const facade=fs.readFileSync(new URL('../web/studio.js',import.meta.url),'utf8');
const ae=fs.readFileSync(new URL('../web/studio_ae_entry.js',import.meta.url),'utf8');
assert.match(facade,/from '\.\/studio_core\.js'/);
assert.match(ae,/from '\.\/studio_core\.js'/);
assert.doesNotMatch(ae,/scripts\/(?:app|api)\.js/);
assert.equal(AE_STUDIO_HOST.schema,STUDIO_HOST_SCHEMA);
const manifest=JSON.parse(fs.readFileSync(new URL('../web/studio_host_manifest.json',import.meta.url),'utf8'));
assert.equal(manifest.hostSchema,STUDIO_HOST_SCHEMA);assert.equal(manifest.uiVersion,AE_STUDIO_HOST.uiVersion);
assert.equal(manifest.entries.ae,'studio_ae.html');
for(const name of ['studio_ae.html','studio_ae_probe.js','studio_ae_entry.js','studio_host_version.js'])assert.match(manifest.entrySha256[name],/^[a-f0-9]{64}$/);
const manifestURL=origin+'/extensions/zura/studio_host_manifest.json';
assert.equal(await verifyStudioHostManifest(manifestURL,origin,async url=>({ok:true,url,json:async()=>manifest})),manifest);
await assert.rejects(()=>verifyStudioHostManifest('http://127.0.0.1:8200/studio_host_manifest.json',origin),/outside this local server/);
await assert.rejects(()=>verifyStudioHostManifest(manifestURL,origin,async url=>({ok:true,url,json:async()=>({...manifest,hostSchema:2})})),/do not match/);
console.log('Shared Studio host contract, local AE API, event ownership and disposal pass.');
