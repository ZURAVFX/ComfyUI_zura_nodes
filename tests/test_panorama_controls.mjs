import assert from 'node:assert/strict';
import {pathToFileURL} from 'node:url';
import {parseHTML} from '../../ui-check/node_modules/linkedom/esm/index.js';
import {cameraOnlyControls} from '../web/studio_panorama_controls.js';

// Run against the installed native session, rather than reproducing its camera maths.
if(!process.env.PANORAMA_ROOT)throw new Error('Set PANORAMA_ROOT to the installed Panorama node directory.');
const native=pathToFileURL(process.env.PANORAMA_ROOT.replaceAll('\\','/')+'/web_src/');
const {loadSceneState}=await import(new URL('pano_scene_state.js',native));
const {evaluateCamera}=await import(new URL('pano_scene_eval.js',native));
const {createStudioSession}=await import(new URL('studio/session.js',native));
const {document}=parseHTML('<html><body><div class="pano-studio-backdrop"><div class="pano-studio-main"><div class="pano-studio-tabs"><button data-value="camera"></button></div><div data-head="camera"><button data-part="name"></button></div><span class="pano-studio-tl-frame">0 / 48</span><button data-tl="play" aria-label="Pause"></button></div></div></body></html>');
globalThis.document=document;
const root=document.querySelector('.pano-studio-backdrop');
const session=createStudioSession({state:loadSceneState({version:2,timeline:{fps:24,length:48},camera:{}})});
let settled=0,redrawn=0,selected=0,cameraView=0,paused=0;
root.querySelector('[data-value="camera"]').onclick=()=>cameraView++;
root.querySelector('[data-part="name"]').onclick=()=>selected++;
root.querySelector('[data-tl="play"]').onclick=e=>{paused++;e.currentTarget.setAttribute('aria-label','Play');};
const dispose=cameraOnlyControls({session,stage:()=>({settle(){settled++;},redraw(){redrawn++;}})},root);
const click=name=>root.querySelector(`[data-${name}]`).click();
assert.equal(cameraView,1);
assert.equal(selected,1);
click('reset-camera');click('key-camera');
const first=evaluateCamera(session.state.camera,0);
assert.equal(first.hFOV_deg,85);
assert.deepEqual(first.position,[0,0,0]);
for(const lane of ['position','rotation','fov','curve'])assert.deepEqual(session.state.camera[lane].keyframes.map(k=>k.frame),[0]);
const keyed=JSON.stringify(session.state);click('key-camera');
assert.equal(JSON.stringify(session.state),keyed,'Repeated keying must not toggle keys off');
root.querySelector('.pano-studio-tl-frame').textContent='47 / 48';
for(const [field,value] of [['position_x',-.2],['yaw_deg',22],['hFOV_deg',72]])session.applyInspector({type:'field',target:{kind:'camera'},field,value,phase:'commit'},{playhead:47});
click('key-camera');
for(const lane of ['position','rotation','fov','curve'])assert.deepEqual(session.state.camera[lane].keyframes.map(k=>k.frame),[0,47]);
const last=evaluateCamera(session.state.camera,47),middle=evaluateCamera(session.state.camera,24);
assert.equal(last.yaw_deg,22);assert.equal(last.position[0],-.2);assert.equal(last.hFOV_deg,72);
assert.ok(middle.yaw_deg>0&&middle.yaw_deg<22,'The native camera interpolates between keyed positions');
assert.deepEqual(evaluateCamera(session.state.camera,0),first,'The first pose stays unchanged');
click('reset-camera');
assert.deepEqual(evaluateCamera(session.state.camera,47),first,'Reset restores the source camera at the current frame');
assert.deepEqual(evaluateCamera(session.state.camera,0),first);
session.undo();
assert.deepEqual(evaluateCamera(session.state.camera,47),last,'Reset is undone in one step');
session.state.camera.locked=true;
const locked=JSON.stringify(session.state);click('reset-camera');click('key-camera');
assert.equal(JSON.stringify(session.state),locked);
assert.match(root.querySelector('[data-camera-status]').textContent,/Unlock/);
assert.equal(paused,1);assert.ok(settled>=6&&redrawn>=5);
dispose();assert.equal(root.querySelector('.zc-camera-toolbar'),null);
assert.equal(root.classList.contains('zc-camera-only'),false);
console.log('Native camera view, all-property keyframes, interpolation, repeat, reset, Undo and lock pass.');
