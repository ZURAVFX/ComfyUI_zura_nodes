import assert from 'node:assert/strict';
import {ContentDetection} from '../web/studio_content.js';
let nextId=0,changes=0;
const timers=new Map(),requests=[];
const detector=new ContentDetection(payload=>new Promise(resolve=>requests.push({payload,resolve})),()=>changes++,{
  setTimer:callback=>{timers.set(++nextId,callback);return nextId;},clearTimer:id=>timers.delete(id)});
const config={subject_mode:'auto',start:0,duration:2,workflow_mode:'motion',length_mode:'custom'};
const source={id:'first',duration:15};
const fire=()=>{const [id,callback]=timers.entries().next().value;timers.delete(id);return callback();};
detector.update(source,config);
assert.equal(detector.badge().label,'Checking subject…');
detector.update(source,config);
assert.equal(timers.size,1,'Repeated renders do not duplicate detection');
detector.update(source,{...config,start:1});
assert.equal(timers.size,1,'Interval changes replace the pending debounce');
const oldRequest=fire();
assert.equal(requests[0].payload.start,1);
detector.update({id:'second',duration:15},config);
const currentRequest=fire();
requests[0].resolve({status:'people',reason:'Old source'});await oldRequest;
assert.equal(changes,0,'Stale replies cannot change the badge');
assert.equal(detector.badge().label,'Checking subject…');
requests[1].resolve({status:'objects',reason:'No human found'});await currentRequest;
assert.equal(detector.badge().label,'No people detected');
assert.equal(changes,1);
detector.update(source,{...config,subject_mode:'people'});
assert.equal(timers.size,0,'Explicit subject guidance does not invoke detection');
assert.equal(detector.badge('people').kind,'people');
detector.update(source,{...config,length_mode:'original',start:8,duration:2,workflow_mode:'viewport'});
const originalRequest=fire();
assert.deepEqual(requests[2].payload,{asset_id:'first',start:0,duration:15,viewport:true});
detector.update(source,{...config,subject_mode:'objects'});
requests[2].resolve({status:'people'});await originalRequest;
assert.equal(detector.badge('objects').kind,'objects','Manual overrides survive in-flight automatic results');
console.log('Content detection is debounced, non-blocking, interval-aware and ignores stale replies and manual overrides.');
