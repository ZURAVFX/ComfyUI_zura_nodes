import assert from 'node:assert/strict';
import {buildInpaintRepairGraph,inpaintAvailability,inpaintValidation,INPAINT_LORA} from '../../web/paintout_studio/inpaint_recipes.js';
import {buildInpaintFrameGraph,FRAME_EDIT_MODELS} from '../../web/paintout_studio/paintout_frame_recipes.js';
import {PAINTOUT_MODELS,buildPaintoutGraph} from '../../web/paintout_studio/paintout_recipes.js';

const c={mode:'inpaint',source:'C:/shots/source.mp4',mask:'C:/shots/mask.mp4',startFrame:10,frameCount:17,sequenceFps:24,width:1152,height:640,sourceColour:'srgb_display',outputMode:'SDR video',anchors:[{file:'C:/shots/frame.png',frame:17,strength:.8}],prompt:'A red bicycle',seed:42};
assert.equal(inpaintValidation(c),'');
assert.match(inpaintValidation({...c,anchors:[]}),/reference frame/);
assert.match(inpaintValidation({...c,mask:''}),/inpaint mask/);
const g=buildInpaintRepairGraph(c);
assert.equal(g.source.inputs.start_frame,10);
assert.equal(g.source.inputs.frame_count,17);
assert.equal(JSON.parse(g.anchors.inputs.anchors)[0].frame,17,'the anchor keeps its original source-frame ID');
assert.equal(g.lora.inputs.lora_name,INPAINT_LORA);
assert.equal(g.lora.inputs.strength_model,1);
assert(!Object.values(g).some(n=>n.class_type==='ZuraPaintoutGuideMemory'));
assert.deepEqual(g.prepare_low.inputs.mask,['mask_low',0]);
assert.deepEqual(g.guide.inputs.image,['prepare_low',0]);
assert.deepEqual(g.apply_anchors.inputs.anchors,['anchors',0]);
assert.deepEqual(g.anchors_high.inputs.anchors,['anchors',0]);
assert.equal(g.sigmas.inputs.sigmas.split(',').length-1,8);
assert.equal(g.sigmas_high.inputs.sigmas.split(',').length-1,2);
assert.deepEqual(g.save.inputs.decoded_crop,['blend_high',0]);
assert.deepEqual(g.save.inputs.plate,['source',2],'original plate and audio remain attached to the final export');
assert.equal(g.save.inputs.match_context,true);
const hdr=buildInpaintRepairGraph({...c,sourceColour:'hlg_rec2020',processingSpace:'HDR (ACEScct)',colourPipeline:'hdr_hdr',outputMode:'EXR + HLG video',anchors:[{...c.anchors[0],file:'C:/shots/frame.exr',colour_space:'acescg'}]});
assert.equal(hdr.video_vae.inputs.vae_name,PAINTOUT_MODELS.hdrVideoVae);
assert.equal(hdr.float_vae.class_type,'LTXVVAEForceFloat32');
assert.equal(hdr.source.inputs.processing_mode,'HDR (ACEScct)');
assert.equal(hdr.save.inputs.export_format,'EXR + HLG video');
const hdrConvert=buildInpaintRepairGraph({...c,colourPipeline:'sdr_hdr',outputMode:'EXR + HLG video'});
assert.deepEqual(hdrConvert.repair_save.inputs.decoded_crop,['blend_high',0]);
assert(!hdrConvert.save,'SDR repair checkpoint precedes a separate HDR conversion');
const normal=buildPaintoutGraph({...c,mode:'targeted'});
assert.equal(normal.lora.inputs.lora_name,PAINTOUT_MODELS.targetedLora,'approved paintout remains separate');

const info={};
for(const n of Object.values(g))info[n.class_type]??={input:{required:{},optional:{}}};
for(const n of ['ZuraPaintoutCrop','ZuraPaintoutGuideMemory','KSampler','LoraLoaderModelOnly','GrowMask','BlockifyMask','InvertMask'])info[n]??={input:{required:{},optional:{}}};
const combo=(n,k,values)=>{info[n].input.required[k]=[values];};
combo('UNETLoader','unet_name',[PAINTOUT_MODELS.model,FRAME_EDIT_MODELS.model]);
combo('CLIPLoader','clip_name',[PAINTOUT_MODELS.text,FRAME_EDIT_MODELS.text]);
combo('CLIPLoader','type',['flux3']);
combo('VAELoader','vae_name',[PAINTOUT_MODELS.videoVae,PAINTOUT_MODELS.audioVae,FRAME_EDIT_MODELS.vae]);
combo('LTXICLoRALoaderModelOnly','lora_name',['nested/'+INPAINT_LORA]);
info.LTXAddVideoICLoRAGuideAdvanced.input.optional.use_streaming=['BOOLEAN',{}];
assert.deepEqual(inpaintAvailability(info,c),{ready:true,missing:[]});
const stockVae=structuredClone(info);combo('VAELoader','vae_name',[PAINTOUT_MODELS.hdrVideoVae,PAINTOUT_MODELS.audioVae,FRAME_EDIT_MODELS.vae]);
assert.deepEqual(inpaintAvailability(info,c),{ready:true,missing:[]},'the official BF16 video VAE is an acceptable fallback');
assert.equal(buildInpaintRepairGraph(c,info).video_vae.inputs.vae_name,PAINTOUT_MODELS.hdrVideoVae);
info.VAELoader=stockVae.VAELoader;
delete info.LTXVLaplacianPyramidBlend;
assert.ok(inpaintAvailability(info,c).missing.includes('LTXVLaplacianPyramidBlend'));

for(const n of ['ZuraPaintoutFrameCrop','ZuraPaintoutFrameComposite','ReferenceMultiLatent','VAEDecode','KSampler','LoadImage'])info[n]??={input:{required:{},optional:{}}};
info.ZuraPaintoutFrameCrop.output=['IMAGE','MASK','ZURA_FRAME_PATCH','INT','INT','IMAGE','IMAGE'];
const frame=buildInpaintFrameGraph({source:c.source,frame:17,mask:'painted mask',prompt:'A red bicycle',references:['zura_images/inpaint_references/bicycle.png']},info);
assert.equal(frame.frame_crop.inputs.frame,17);
assert.deepEqual(frame.frame_reference.inputs['images.image0'],['frame_crop',0]);
assert.deepEqual(frame.frame_reference.inputs['images.image1'],['object_reference_0',0]);
assert.equal(frame.object_reference_0.inputs.image,'zura_images/inpaint_references/bicycle.png');
assert.match(frame.frame_positive.inputs.text,/red bicycle/);
assert.doesNotMatch(frame.frame_positive.inputs.text,/empty ground|do not add a vehicle/i);
assert.deepEqual(frame.frame_save.inputs.patch,['frame_crop',2]);
assert.throws(()=>buildInpaintFrameGraph({source:c.source,frame:17,mask:'x',references:['../escape.png']},info),/Upload/);
console.log('Inpaint conditioning, source IDs, reference images, SDR/HDR paths and independent paintout checks passed.');
